export function renderServices(servicesData) {
  if (!servicesData) return;

  const headerTitle = document.getElementById('services-title');
  const headerSubtitle = document.getElementById('services-subtitle');
  const gridContainer = document.getElementById('services-grid');

  if (headerTitle && servicesData.title) {
    headerTitle.textContent = servicesData.title;
  }

  if (headerSubtitle && servicesData.subtitle) {
    headerSubtitle.textContent = servicesData.subtitle;
  }

  if (gridContainer && Array.isArray(servicesData.items)) {
    gridContainer.innerHTML = servicesData.items
      .map((item) => {
        const iconSvg = iconSvgs[item.icon] || iconSvgs['book-open'];
        return `
          <article class="service-card">
            <div class="service-icon-box" aria-hidden="true">
              ${iconSvg}
            </div>
            <h3 class="service-card-title">${escapeHtml(item.title)}</h3>
            <p class="service-card-desc">${escapeHtml(item.description)}</p>
          </article>
        `;
      })
      .join('');
  }
}
